/// Vanilla `igniteOdds`: how readily fire spreads onto `block`.
#[must_use]
pub fn ignite_odds(block: BlockRef) -> i32 {
    FLAMMABILITY
        .get(block.id())
        .map_or(0, |&(ignite, _)| i32::from(ignite))
}

/// Vanilla `burnOdds`: how readily fire destroys `block`.
#[must_use]
pub fn burn_odds(block: BlockRef) -> i32 {
    FLAMMABILITY
        .get(block.id())
        .map_or(0, |&(_, burn)| i32::from(burn))
}
